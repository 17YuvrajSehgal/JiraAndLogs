"""T12: does agent v3's causal chain point at the file that actually held
the defect, and does v3 lose less than other systems when the answer key
tightens from fix gold to causal gold?

Two separate questions, two separate populations, and they must not be
mixed:

1. The RANKING against causal gold. Handled by score_causal_gold.py --v3,
   which reuses T4's machinery on T4's instances. Only each system's own
   fix-vs-causal gap is read from there. Cross-system comparison involving
   `remember` or `remember_v3` is confounded on that subset, because the
   annotation sample's core stratum was balanced on v2's own outcome.

2. The CHAIN itself, which only v3 produces. Measured here over the whole
   4,409-instance eval split, and over the causal-gold subset where an
   independent label exists.

Usage:
    python industry-c7/scripts/causal_lift_v3.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AG, RES, CG = ROOT / "data/agent", ROOT / "data/results", ROOT / "data/causal-gold"
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from localize import is_dead_row  # noqa: E402


def jsonl(p):
    return [json.loads(l) for l in Path(p).open(encoding="utf-8") if l.strip()]


def chain_files(r) -> set:
    return {(s.get("file") or "").strip()
            for s in (r.get("causal_chain") or []) if (s.get("file") or "").strip()}


def main() -> int:
    rows = [r for r in jsonl(AG / "agent-v3-full.jsonl")
            if not is_dead_row(r)]
    gold = {(r["project"], r["issue_key"]): r for r in jsonl(CG / "causal-gold.jsonl")}

    n = len(rows)
    chained = [r for r in rows if r.get("causal_chain")]
    withf = [r for r in rows if chain_files(r)]
    hit_fix = [r for r in withf if chain_files(r) & set(r["gold_files"])]
    consistent = [r for r in withf if r["ranking"] and r["ranking"][0] in chain_files(r)]
    steps = sum(len(r["causal_chain"]) for r in chained)

    # The labelled subset: an independent judgement of which gold file is causal.
    sub = [r for r in withf
           if gold.get((r["project"], r["issue_key"]), {}).get("causal_gold")]
    sfix = [r for r in sub
            if chain_files(r) & set(gold[(r["project"], r["issue_key"])]["fix_gold"])]
    scau = [r for r in sub
            if chain_files(r) & set(gold[(r["project"], r["issue_key"])]["causal_gold"])]

    out = {
        "n_instances": n,
        "n_with_chain": len(chained),
        "mean_steps": round(steps / max(len(chained), 1), 2),
        "n_chain_names_a_file": len(withf),
        "share_chain_names_a_file": round(len(withf) / n, 4),
        "share_chain_hits_fix_gold": round(len(hit_fix) / max(len(withf), 1), 4),
        "share_chain_contains_ranked_top1": round(len(consistent) / max(len(withf), 1), 4),
        "labelled": {
            "n": len(sub), "n_hits_fix": len(sfix), "n_hits_causal": len(scau),
            "share_causal_given_fix_hit":
                round(len(scau) / len(sfix), 4) if sfix else None,
        },
    }
    (RES / "causal-lift-v3.json").write_text(json.dumps(out, indent=1) + "\n",
                                             encoding="utf-8")

    sc = json.load((RES / "causal-gold-scores-v3.json").open(encoding="utf-8"))
    S = sc["systems"]
    order = [("remember_v3", "REMEMBER v3"), ("remember", "REMEMBER v2"),
             ("llm_twostage", "Model alone"), ("llm_rerank", "Model re-rank"),
             ("cond_ours", "Retrieval + incident memory"),
             ("content_bm25", "Lexical log-to-code")]
    gaps = "\n".join(
        f"| {lab} | {S[k]['fix']['acc@5']*100:.1f}% | {S[k]['causal']['acc@5']*100:.1f}% | "
        f"{S[k]['gap']['acc@5']['delta']*100:+.1f} "
        f"[{S[k]['gap']['acc@5']['lo']*100:+.1f}, {S[k]['gap']['acc@5']['hi']*100:+.1f}] |"
        for k, lab in order if k in S)

    no_file = 100 - out["share_chain_names_a_file"] * 100
    no_gold = 100 - out["share_chain_hits_fix_gold"] * 100
    lab = out["labelled"]

    doc = f"""# T12: causal lift of agent v3

Generated by `scripts/causal_lift_v3.py`. Nothing here is typed by hand.

Review-2, Priority 3 asks for a structured strategy that forces a chain of
evidence from symptom to suspected cause, and for that chain to be measured
rather than asserted. v3 makes the chain required by the submission schema.
This is what it bought.

## 1. The chain exists, and it is attached to the prediction

Over the full {out['n_instances']:,}-instance evaluation split:

| | |
|---|---|
| predictions carrying a causal chain | **{out['n_with_chain']:,} / {out['n_instances']:,}** (100%) |
| mean steps per chain | {out['mean_steps']} |
| chains naming at least one file | {out['n_chain_names_a_file']:,} ({out['share_chain_names_a_file'] * 100:.1f}%) |
| of those, chain names a fix-gold file | {out['share_chain_hits_fix_gold'] * 100:.1f}% |
| of those, chain contains the ranked top-1 | **{out['share_chain_contains_ranked_top1'] * 100:.1f}%** |

The last row is the one that matters for whether the chain is real. A chain
that named files unrelated to the system's own answer would be decoration
written to satisfy the schema. At {out['share_chain_contains_ranked_top1'] * 100:.1f}%
the chain and the ranking are the same claim.

{no_file:.1f}% of chains name no file at all. They are reasoning steps
quoting the report and read code without binding a step to a path, which the
schema permits. The paper should say so rather than quote the file-naming
figure as if it were universal.

## 2. When the chain points at a gold file, that file is causal

On the subset with an independent causal label (n = {lab['n']}):

| | |
|---|---|
| chain names a fix-gold file | {lab['n_hits_fix']} / {lab['n']} |
| chain names a causal-gold file | {lab['n_hits_causal']} / {lab['n']} |
| **causal share, given the chain hit fix gold** | **{lab['share_causal_given_fix_hit'] * 100:.0f}%** ({lab['n_hits_causal']}/{lab['n_hits_fix']}) |

Not one chain in this subset pointed at a fix-modified file that the
annotation calls `symptom-handling`, `preventive`, `refactor` or `test`.
With n = {lab['n_hits_fix']} the interval around 100% is wide and the paper
must give the count, not the percentage alone.

## 3. The ranking loses least when the answer key tightens

Acc@5 on T4's {sc['n_scored']} instances, same rankings, two answer keys.

| system | vs fix gold | vs causal gold | gap, 95% CI |
|---|---|---|---|
{gaps}

**Read only the gap column across rows.** The absolute columns cannot be
compared between `REMEMBER v2` and `REMEMBER v3`, nor between either of them
and the other systems, because the annotation sample's core stratum was
balanced on `(v2 right/wrong) x (hard/easy)` using v2's own output. Half
these instances are ones v2 got wrong. v2 scores 0.620 Acc@5 here against
0.903 on the full 790; v3 did not exist when the sample was drawn and takes
no equivalent hit. On the full 790 the two are statistically indistinguishable
(Acc@5 delta -0.0025, 95% CI [-0.0165, +0.0114]).

## What this does and does not show

- **Does:** every v3 prediction carries a chain; the chain is the same claim
  as the ranking; where an independent causal label exists, the chain's file
  is causal every time it is gold at all.
- **Does not:** show that v3 ranks better than v2. It does not. The chain is
  the contribution, not an accuracy gain.
- **Does not:** validate the {no_gold:.1f}% of file-naming chains that name
  no gold file. Whether those are wrong or merely pointing somewhere the fix
  did not touch is unmeasured, and is what T16 and T18 are for.
"""
    (ROOT / "paper" / "causal-lift-v3.md").write_text(doc, encoding="utf-8")
    print(json.dumps(out, indent=1))
    print("\nwrote paper/causal-lift-v3.md and data/results/causal-lift-v3.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
